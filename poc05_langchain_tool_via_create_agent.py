from dotenv import load_dotenv
from langchain.agents import create_agent
from langchain_core.tools import tool
# Import the built-in Wikipedia tools
from langchain_community.tools import WikipediaQueryRun
from langchain_community.utilities import WikipediaAPIWrapper
from langchain_groq import ChatGroq

load_dotenv()

# =====================================================================
# 1. DEFINE A CUSTOM TOOL
# =====================================================================
@tool
def calculate_word_count(text: str) -> int:
    """Counts the total number of words in a given text string."""
    return len(text.split())

# =====================================================================
# 2. INITIALISE AN ALTERNATIVE IN-BUILT TOOL (WIKIPEDIA)
# =====================================================================
# Set up the Wikipedia API wrapper (limits the payload length for the LLM)
wiki_wrapper = WikipediaAPIWrapper(top_k_results=1, doc_content_chars_max=500)
# Package the wrapper into the standard LangChain tool format
wikipedia_tool = WikipediaQueryRun(api_wrapper=wiki_wrapper)

# Combine both tools into a single list
tools = [calculate_word_count, wikipedia_tool]

# =====================================================================
# 3. PROVISION AUTOMATED AGENT
# =====================================================================
# Ensure OPENAI_API_KEY is available in your environment variables!
# e.g., os.environ["OPENAI_API_KEY"] = "your-api-key"

llm = ChatGroq(model="qwen/qwen3.8-27b", temperature=0)

# create_agent orchestrates the agent loop. It automatically fires tools 
# whenever the LLM asks for them and channels responses back natively.
agent = create_agent(model=llm, tools=tools)

# =====================================================================
# 4. CONVERSATIONAL RUNTIME TESTS
# =====================================================================
def run_agent_query(user_query: str):
    print(f"\nUser: {user_query}")
    
    # Run the query through the automatic loop execution environment
    response = agent.invoke({
        "messages": [{"role": "user", "content": user_query}]
    })
    
    # Print out the final conversation response generated by the model
    print(f"Agent Final Answer: {response['messages'][-1].content}")

# Test Case 1: Triggering the In-Built Wikipedia tool automatically
run_agent_query("Summarise who Alan Turing was based on Wikipedia data.")

# Test Case 2: Triggering the Custom Word Count tool automatically
run_agent_query("Count how many words are in this string: 'LangChain automation rocks!'")